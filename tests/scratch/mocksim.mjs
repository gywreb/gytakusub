// Offline replay of browser/run.mjs: stamp the page like page.js, answer like mock-api.mjs, lay out.
import fs from "node:fs";
import { createCanvas, loadImage } from "canvas";
import { analyzePage } from "../cv-node.mjs";
import { layout } from "../../extension/engine/layout.js";
import { stampMarks } from "../../extension/engine/page.js";
import { startMock } from "../browser/mock-api.mjs";
const img = await loadImage("fixtures/demo-page.png");
const scale = Math.min(1, 1600 / Math.max(img.width, img.height)); const W = Math.round(img.width * scale), H = Math.round(img.height * scale);
const c = createCanvas(W, H), ctx = c.getContext("2d"); ctx.drawImage(img, 0, 0, W, H);
const an = await analyzePage(ctx.getImageData(0, 0, W, H));
for (const r of an.regions) console.log("R", r.id, r.kind, JSON.stringify(r.box));
stampMarks(ctx, an.regions, W);
fs.writeFileSync("/tmp/stamped.png", c.toBuffer("image/png"));
const { srv } = await startMock(18999, "fixtures/demo-page.png", { truth: "fixtures/demo-truth.json", badBoxes: process.argv.includes("--bad") });
const body = { messages: [{ content: [{ type: "text", text: `regions (1-${an.regions.length})` }, { type: "image", source: { data: fs.readFileSync("/tmp/stamped.png").toString("base64") } }] }] };
const res = await (await fetch("http://127.0.0.1:18999/v1/messages", { method: "POST", body: JSON.stringify(body) })).json();
srv.close();
const items = JSON.parse(res.content[0].text).items.map((it, index) => ({ ...it, box: [it.box[0] / W, it.box[1] / H, it.box[2] / W, it.box[3] / H], index }));
for (const it of items) console.log("I", it.tag, it.box.map((v, i) => Math.round(v * (i % 2 ? H : W))).join(","));
const { placements } = layout(an, items);
for (const p of placements) console.log("P", p.tag, p.item, JSON.stringify({ x: Math.round(p.rect.x), y: Math.round(p.rect.y) }), p.halo ? "halo" : "");
an.dispose();
