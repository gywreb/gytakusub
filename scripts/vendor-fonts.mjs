// The lettering fonts, in the order text.js tries them, and which characters each one has:
// writes extension/vendor/lettering-fonts.js (a classic script exposing globalThis.GyFonts, for
// the page script, the web app and the tests).
//   node scripts/vendor-fonts.mjs
// A page is lettered in the first font that has every letter of its translations, so a word is
// never drawn in two fonts (the browser's per-character fallback mixes them: Vietnamese "người"
// came out with its ư in another font). The coverage comes from each font's own character map.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

// family: the name the pages register the file under (content.js, web/style.css, the tests).
export const FONTS = [
  { family: "Gytakusub Comic", file: "fonts/ComicNeue-Bold.ttf", name: "Comic Neue Bold" },
  { family: "Gytakusub Comic Relief", file: "fonts/ComicRelief-Bold.ttf", name: "Comic Relief Bold" }, // + Latin Extended, Cyrillic, Greek
  { family: "Gytakusub Mali", file: "fonts/Mali-Bold.ttf", name: "Mali Bold" }, // + Vietnamese, Thai
];

/** Code points mapped by a TrueType/OpenType font (cmap formats 4 and 12), plus its cap height. */
export function readFont(buf) {
  const u16 = (o) => buf.readUInt16BE(o), u32 = (o) => buf.readUInt32BE(o), i16 = (o) => buf.readInt16BE(o);
  const tables = {};
  for (let i = 0, n = u16(4); i < n; i++) { const r = 12 + i * 16; tables[buf.toString("latin1", r, r + 4)] = u32(r + 8); }
  if (tables.cmap == null || tables.head == null) throw new Error("not a TrueType/OpenType font");
  const upem = u16(tables.head + 18);
  const os2 = tables["OS/2"];
  const cap = os2 != null && u16(os2) >= 2 ? i16(os2 + 88) / upem : 0.7;
  const cmap = tables.cmap, subtables = [];
  for (let i = 0, n = u16(cmap + 2); i < n; i++) {
    const r = cmap + 4 + i * 8, platform = u16(r), encoding = u16(r + 2), off = cmap + u32(r + 4);
    if (platform === 3 && (encoding === 1 || encoding === 10) || platform === 0) subtables.push(off);
  }
  const cps = new Set();
  for (const off of subtables) {
    const format = u16(off);
    if (format === 4) {
      const segX2 = u16(off + 6), ends = off + 14, starts = ends + segX2 + 2, deltas = starts + segX2, ranges = deltas + segX2;
      for (let s = 0; s < segX2 / 2; s++) {
        const end = u16(ends + s * 2), start = u16(starts + s * 2), delta = i16(deltas + s * 2), roff = u16(ranges + s * 2);
        for (let c = start; c <= end && c !== 0xffff; c++) {
          let glyph;
          if (roff === 0) glyph = (c + delta) & 0xffff;
          else { const g = u16(ranges + s * 2 + roff + (c - start) * 2); glyph = g === 0 ? 0 : (g + delta) & 0xffff; }
          if (glyph) cps.add(c);
        }
      }
    } else if (format === 12) {
      for (let g = 0, n = u32(off + 12); g < n; g++) {
        const r = off + 16 + g * 12, start = u32(r), end = u32(r + 4), glyph = u32(r + 8);
        for (let c = start; c <= end; c++) if (glyph + (c - start)) cps.add(c);
      }
    }
  }
  return { cap: Math.round(cap * 1000) / 1000, codepoints: [...cps].sort((a, b) => a - b) };
}

/** [[first, last], …] runs of consecutive code points. */
export function toRanges(cps) {
  const out = [];
  for (const c of cps) { const last = out.at(-1); if (last && c === last[1] + 1) last[1] = c; else out.push([c, c]); }
  return out;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const entries = FONTS.map((f) => {
    const { cap, codepoints } = readFont(fs.readFileSync(path.join(root, "extension", f.file)));
    return { family: f.family, file: f.file, weight: 700, cap, ranges: toRanges(codepoints), glyphs: codepoints.length, name: f.name };
  });
  const out = `// The lettering fonts and their characters. Generated by scripts/vendor-fonts.mjs from the font files; do not edit.
((root) => {
root.GyFonts = ${JSON.stringify(entries.map(({ family, file, weight, cap, ranges }) => ({ family, file, weight, cap, ranges })))};
})(typeof globalThis !== "undefined" ? globalThis : this);
`;
  fs.writeFileSync(path.join(root, "extension/vendor/lettering-fonts.js"), out);
  for (const e of entries) console.log(`${e.name}: ${e.glyphs} characters in ${e.ranges.length} runs, cap height ${e.cap} em`);
}
